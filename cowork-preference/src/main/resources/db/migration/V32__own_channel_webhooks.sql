CREATE TABLE tb_webhooks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id UUID NOT NULL DEFAULT gen_random_uuid(),
    channel_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    avatar_url VARCHAR(512),
    is_secure BOOLEAN NOT NULL,
    secret_hash CHAR(64),
    is_active BOOLEAN NOT NULL DEFAULT true,
    deleted BOOLEAN NOT NULL DEFAULT false,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    mode_changed_at TIMESTAMPTZ,
    CONSTRAINT uq_tb_webhooks_execution_id UNIQUE (execution_id),
    CONSTRAINT ck_tb_webhooks_execution_id_v4 CHECK (
        execution_id::text ~ '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
    ),
    CONSTRAINT ck_tb_webhooks_secret CHECK (
        (deleted AND secret_hash IS NULL) OR
        (NOT deleted AND ((is_secure AND secret_hash IS NOT NULL AND secret_hash ~ '^[0-9a-f]{64}$') OR (NOT is_secure AND secret_hash IS NULL)))
    )
);
COMMENT ON COLUMN tb_webhooks.execution_id IS 'Random UUIDv4 for the inbound webhook URL; immutable after assignment';
COMMENT ON COLUMN tb_webhooks.channel_id IS 'cowork-channel.tb_channels.id; Kafka lifecycle projection';
COMMENT ON COLUMN tb_webhooks.created_by IS 'cowork-user.tb_accounts.id; creating account ID';
CREATE INDEX idx_tb_webhooks_channel_id ON tb_webhooks (channel_id);

CREATE TABLE tb_webhook_operations (
    actor_id BIGINT NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    response JSONB NOT NULL,
    secret_ciphertext TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (actor_id, idempotency_key)
);
COMMENT ON COLUMN tb_webhook_operations.actor_id IS 'cowork-user.tb_accounts.id; requesting account ID';
COMMENT ON COLUMN tb_webhook_operations.secret_ciphertext IS 'AES-256-GCM encrypted one-time response; never published to Kafka';

